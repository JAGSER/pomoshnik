// example.js: «Одна фигура, весь помощник», переписано на MORF (120 BPM, доля 0,5 с)
const M = MORF, C = M.C, B = 0.5;

// состояния фигуры: [t, вид, w, h, r, цвет 0 чёрный..1 белый, зум]; все t на долях
const S = M.states([
  [0 * B, 'btn', 440, 140, 70, 0, 1.6],
  [1 * B, 'load', 140, 140, 70, 0, 2.2],
  [3 * B, 'check', 150, 150, 75, 0, 2.2],
  [4 * B, 'island', 620, 124, 62, 0, 1.4],
  [6 * B, 'player', 780, 460, 60, 1, 1.12],
  [10 * B, 'vol', 720, 160, 80, 1, 1.0],
  [13 * B, 'tog', 300, 170, 85, 0.84, 1.9],
  [14 * B, 'tog', 300, 170, 85, 0.07, 1.9],
  [15 * B, 'tabs', 840, 150, 75, 1, 1.08],
  [18 * B, 'chart', 840, 640, 48, 1, 1.08],
  [22 * B, 'cmd', 840, 560, 44, 1, 1.08],
  [25 * B, 'toast', 680, 140, 70, 0, 1.35],
  [28 * B, 'btn', 440, 140, 70, 0, 1.6]
]);

// заголовки над фигурой: смена на ключевом слове фразы, *слово* = акцент
const CAP = [
  [0, 2.5, 'Одна *кнопка*'],
  [2.5, 5, 'Читает *вслух*'],
  [5, 6.5, '*Своя* громкость'],
  [6.5, 7.5, '*Живой* режим'],
  [7.5, 9, 'Всё *рядом*'],
  [9, 11, '*Рейтинг* товара'],
  [11, 12.5, 'Пара *букв*'],
  [12.5, 14, 'Ответ *готов*'],
  [14, 99, 'Помощник *AI*']
];

// курсор: [t, x, y] от центра фигуры в её координатах; конец совпадает с началом
const CK = [[0, 170, 120], [0.15, 60, 12], [0.7, 150, 130], [2.5, 12, 160], [3.55, -188, 55], [4.05, 175, 55],
  [4.85, 10, 8], [5.3, 420, 8], [6.15, 260, 90], [6.55, 20, 25], [7.6, 10, 20], [8.1, 283, 20], [8.75, 300, 110],
  [9.5, 232, -90], [10.55, -250, -215], [11.2, 330, -30], [11.75, 150, -90], [12.3, 300, 120], [13.6, 200, 15], [14.3, 170, 120]];
// клики: [t, удержание]; длинные удержания = перетаскивание
const CL = [[0.5, .12], [3.5, .12], [4, .75], [5.25, .75], [7, .12], [8, .12], [8.5, .12], [11, .12], [12, .12], [13.95, .12]];

// плеер: при зажатии прогресс считается из позиции курсора на дорожке
const PGEO = M.playerGeo({ w: 780, h: 460 });
function progv(t) {
  const P = 4.0, R = 4.75;
  const at = u => M.clamp((M.curPos(CK, u).x - PGEO.x0) / PGEO.len, 0, 1);
  if (t < P) return 0.2 + 0.03 * Math.max(0, t - 3.5);
  return t < R ? at(t) : at(R) + 0.03 * (t - R);
}

// громкость: тянем за максимум, дорожка резиново растягивается и возвращается
function volS(t) {
  const P = 5.25, R = 6.0;
  if (t < P) return { v: 0.6, ext: 0 };
  const sv = M.sliderVal(M.curPos(CK, Math.min(t, R)).x, { w: 720 });
  return { v: sv.v, ext: M.stretch(sv.over) * M.relax(t, R) };
}

const knob = (t, a, b) => M.sp(t - a, 26, .8) - M.sp(t - b, 26, .8);

// содержимое состояний: координаты от центра фигуры
const UI = {
  btn: (t, i) => M.uiButton(t, i, { label: 'Спросить' }),
  load: (t, i) => M.uiLoader(t, i),
  check: (t, i) => M.uiCheck(t, i, { t0: 1.55 }),
  island: (t, i) => M.uiIsland(t, i, { label: 'Слушаю' }),
  player: (t, i) => M.uiPlayer(t, i, {
    title: 'Читает вслух', sub: 'Инструкция к лекарству', p: progv(t), total: 190,
    q: M.sp(t - 3.5, 22, .8), knob: knob(t, 4, 4.75)
  }),
  vol: (t, i) => { const s = volS(t); M.uiSlider(t, i, { v: s.v, ext: s.ext, knob: knob(t, 5.25, 6) }); },
  tog: (t, i) => M.uiToggle(t, i, [[0, 0], [7, 1]]),
  tabs: (t, i) => M.uiTabs(t, i, ['Чат', 'Камера', 'Рейтинг'], [[7.5, 0], [8, 1], [8.5, 2]]),
  chart: (t, i) => M.uiChart(t, i, {
    title: 'Рейтинг товара', label: '7 дней',
    values: [3.1, 3.6, 3.4, 4.1, 3.9, 4.8, 4.5], days: ['Пн', 'Вт', 'Ср', 'Чт', 'Пт', 'Сб', 'Вс'],
    t0: 9.1, dur: 0.9, tip: { i: 5, t0: 10, t1: 10.95, text: '4,8 из 5' }
  }),
  cmd: (t, i) => M.uiPalette(t, i, {
    items: ['Лекарство: дозировка', 'Перевести меню', 'Сделать ролик', 'Включить камеру'],
    query: 'лек', at: 11.25, step: 0.25, enter: 12, placeholder: 'Найти команду'
  }),
  toast: (t, i) => M.uiToast(t, i, { text: 'Готово: ответ прочитан', t0: 12.65 })
};

function draw(t, k) {
  M.begin(k);
  const st = M.stateAt(S, t);
  // фон с сеткой точек: лёгкий параллакс от зума камеры
  M.bg(t, st.cam);
  // заголовок по словам, акцент на ключевом слове
  M.caption(t, CAP, { y: 540, size: 112 });
  // финальная подпись под заголовком
  if (t >= 14.3) M.words(t, 14.3, 'для всей семьи', 540, 640, { size: 48, weight: 500, color: C.dim, rise: 16, stagger: .08 });
  // ряд долей: каждая доля подпрыгивает
  M.beatBar(t, { n: 32, y: 1600 });
  // фигура: растяжение громкости расширяет и саму фигуру
  const pr = M.press(t, CL);
  const ext = t >= 5.25 && t < 6.9 ? volS(t).ext : 0;
  const H = M.hero(S, t, UI, { press: pr, ext });
  // курсор ведёт каждое изменение
  M.cursor(t, H, CK, pr);
}

